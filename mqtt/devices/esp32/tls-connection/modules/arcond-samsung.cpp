void processACCommand(int valor) {
  if (valor == 7) {
    sendACRaw(AC_OFF, 3);
    Serial.println("AC - Desligado");
  }
  else if (valor >= AC_TEMP_MIN && valor <= AC_TEMP_MAX) {
    sendACRaw(AC_TEMP_TABLE[valor - AC_TEMP_MIN]);
    Serial.printf("AC - Temperatura: %d°C\n", valor);
  }
  else {
    Serial.printf("AC - Comando invalido: %d\n", valor);
  }
}

